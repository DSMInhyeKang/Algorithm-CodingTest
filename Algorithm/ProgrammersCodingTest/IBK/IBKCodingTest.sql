-- 상품을 구매한 회원 비율 구하기
SELECT YEAR(O.SALES_DATE) AS YEAR,
    MONTH(O.SALES_DATE) AS MONTH,
    COUNT(DISTINCT O.USER_ID) AS PURCHASED_USERS,
    ROUND(
        COUNT(DISTINCT O.USER_ID) /
        (SELECT COUNT(*) FROM USER_INFO WHERE YEAR(JOINED) = 2021)  -- 서브쿼리 안 쓰면 >> 2021년에 가입한 회원 중 << 분모 조건 미성립
    , 1) AS PUCHASED_RATIO
FROM USER_INFO AS U INNER JOIN ONLINE_SALE AS O ON U.USER_ID = O.USER_ID
WHERE YEAR(U.JOINED) = 2021  -- U.JOINED LIKE '2021%' 등 DATE 타입에도 LIKE사용 가능
GROUP BY YEAR, MONTH
ORDER BY YEAR ASC, MONTH ASC;



