-- 특정 기간동안 대여 가능한 자동차들의 대여비용 구하기
SELECT C.CAR_ID, C.CAR_TYPE, FLOOR(C.DAILY_FEE*30*(100-P.DISCOUNT_RATE) / 100) AS FEE
FROM CAR_RENTAL_COMPANY_CAR AS C INNER JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN AS P ON C.CAR_TYPE = P.CAR_TYPE
WHERE C.CAR_TYPE IN ('세단', 'SUV') 
    AND P.DURATION_TYPE = '30일 이상' 
    AND C.CAR_ID NOT IN (
        SELECT CAR_ID 
        FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY AS H 
        WHERE H.END_DATE >= '2022-11-01' AND H.START_DATE <= '2022-11-30'
    )  
GROUP BY C.CAR_ID, C.CAR_TYPE HAVING FEE >= 500000 AND FEE < 2000000  -- HAVING 안 쓸거면 FLOOR(~) 계산식을 WHERE에 넣고 비교해야함
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC;

-- another verion
