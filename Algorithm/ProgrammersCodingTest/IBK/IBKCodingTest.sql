-- 대여 횟수가 많은 자동차들의 월별 대여 횟수 구하기
SELECT MONTH, CAR_ID, RECORDS 
FROM (
    SELECT DISTINCT MONTH(START_DATE) AS MONTH, CAR_ID,  -- OVER(윈도우함수) 쓰면 중복 제거 X.(기존 행에 칼럼만 추가)
        COUNT(*) OVER(PARTITION BY CAR_ID) AS CAR_TOTAL
        COUNT(*) OVER(PARTITION BY MONTH(START_DATE), CAR_ID) AS RECORDS
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE START_DATE BETWEEN '2022-08-01' AND '2022-10-31'
) AS T
WHERE CAR_TOTAL >= 5 AND RECORDS > 0  -- WHERE 서브쿼리로 일치하는 자동차ID를 거른다면 어차피 내부+외부 다 GROUP BY+HAVING에서 개수 필터링
-- GROUP BY MONTH, CAR_ID   -- 바깥에서 GROUP BY를 한 번 더 쓰거나, 서브쿼리 내에서 DISTINCT 사용 등 중복제거 요함.(상황별 성능 차이)
ORDER BY MONTH ASC, CAR_ID DESC;



-- 입양 시각 구하기(2)
