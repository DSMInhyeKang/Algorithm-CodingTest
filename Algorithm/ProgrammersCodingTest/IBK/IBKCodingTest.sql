FROM (
    SELECT CATEGORY, PRICE, PRODUCT_NAME, 
        RANK() OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC) AS RANKING  -- GROUP BY 쓰면 안 되니까(NAME 유실) PARTITION BY
    FROM FOOD_PRODUCT
    WHERE CATEGORY IN ('과자', '국', '김치', '식용유') 
) AS T
WHERE RANKING = 1
ORDER BY MAX_PRICE DESC;



