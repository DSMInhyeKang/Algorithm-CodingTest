WHERE C.CAR_TYPE IN ('세단', 'SUV') AND P.DURATION_TYPE = '30일 이상'
GROUP BY C.CAR_ID, C.CAR_TYPE 
HAVING SUM(CASE WHEN H.START_DATE <= '2022-11-30' AND H.END_DATE >= '2022-11-01' THEN 1 ELSE 0 END) = 0
    AND FEE BETWEEN 500000 AND 1999999 
-- 서브쿼리 안 쓰고 비교하려면 LEFT JOIN하고 Having에 CASE WHEN 쓸 수 있음. BUT H는 여기만 쓰이는데 JOIN하면 오히려 결과 누락될 가능성도 있음.
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC;



