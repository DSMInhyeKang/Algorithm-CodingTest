-- 자동차 대여 기록 별 대여 금액 구하기
SELECT H.HISTORY_ID, 
    ROUND(
        C.DAILY_FEE * (DATEDIFF(H.END_DATE, H.START_DATE) + 1)  
        * (1 - IFNULL(P.DISCOUNT_RATE, 0) / 100), 0
    ) AS FEE
FROM CAR_RENTAL_COMPANY_CAR AS C
INNER JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY AS H ON C.CAR_ID = H.CAR_ID
LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN AS P ON C.CAR_TYPE = P.CAR_TYPE 
    AND P.DURATION_TYPE = (
        CASE
            WHEN DATEDIFF(H.END_DATE, H.START_DATE) + 1 >= 90 THEN '90일 이상'
            WHEN DATEDIFF(H.END_DATE, H.START_DATE) + 1 >= 30 THEN '30일 이상'
            WHEN DATEDIFF(H.END_DATE, H.START_DATE) + 1 >= 7 THEN '7일 이상'
            ELSE NULL
        END
    )   -- 자동차 종류와 대여 기간이 모두 일치하는 것에 한해서 LEFT JOIN
WHERE C.CAR_TYPE = '트럭'
GROUP BY H.HISTORY_ID
ORDER BY FEE DESC, H.HISTORY_ID DESC;



-- 언어별 개발자 분류하기
SET @FRONT := (SELECT SUM(CODE) FROM SKILLCODES WHERE CATEGORY LIKE 'FRONT%');
SET @PYTHON := (SELECT CODE FROM SKILLCODES WHERE NAME = 'PYTHON');
SET @C_SHARP := (SELECT CODE FROM SKILLCODES WHERE NAME = 'C#');

SELECT
    CASE
        WHEN (SKILL_CODE & @FRONT) AND SKILL_CODE & @PYTHON THEN 'A'
        WHEN SKILL_CODE & @C_SHARP THEN 'B'
        WHEN SKILL_CODE & @FRONT THEN 'C'
        ELSE NULL
    END AS GRADE, ID, EMAIL
FROM DEVELOPERS
GROUP BY GRADE, ID, EMAIL HAVING GRADE IS NOT NULL  
-- NOT NULL 필터링용 HAVING + GROUP BY 사용(FROM절에 SELECT~FROM DEVELOPERS까지를 서브쿼리로 넣으면 WHERE에서 필터링 가능)
ORDER BY GRADE ASC, ID ASC;