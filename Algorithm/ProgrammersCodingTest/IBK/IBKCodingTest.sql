-- 그룹별 조건에 맞는 식당 목록 출력하기
WITH HEAVY_REVIEWER AS (
    SELECT MEMBER_ID, RANK() OVER (ORDER BY COUNT(*) DESC) AS RANKING
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
)
-- 1) FROM / JOIN  ->  2) WHERE  ->  3) GROUP BY  ->  4) HAVING  ->  5) SELECT  -> 6) ORDER BY / LIMIT
-- 윈도우함수 RANK()는 4단계 종료 이후 수행이 되므로 CTE에서는 사용 불가함

SELECT M.MEMBER_NAME, R.REVIEW_TEXT, DATE_FORMAT(R.REVIEW_DATE, '%Y-%m-%d') AS REVIEW_DATE
FROM MEMBER_PROFILE AS M INNER JOIN REST_REVIEW AS R ON M.MEMBER_ID = R.MEMBER_ID
WHERE M.MEMBER_ID IN (SELECT MEMBER_ID FROM HEAVY_REVIEWER WHERE RANKING = 1)  -- 그래서 서브쿼리로 순위검증
ORDER BY R.REVIEW_DATE ASC, R.REVIEW_TEXT ASC;



